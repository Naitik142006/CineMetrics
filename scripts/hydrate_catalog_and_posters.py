    # Update upcoming tentpoles with verified dates and posters
    updated_upcoming = []
    for t in CURATED_UPCOMING_TENTPOLES:
        cid = t["canonical_id"]
        item = dict(t)
        if cid in UPCOMING_DATE_MAP:
            new_date, new_year = UPCOMING_DATE_MAP[cid]
            item["release_date"] = new_date
            item["release_year"] = new_year
        if cid in UPCOMING_POSTER_MAP:
            p_path, b_path = UPCOMING_POSTER_MAP[cid]
            item["poster_path"] = p_path
            item["backdrop_path"] = b_path
        updated_upcoming.append(item)

    # Format Python file
    content = '"""\nCineMetrics — Curated Theatrical Catalog\nContains:\n1. CURATED_UPCOMING_TENTPOLES (Future releases >= Nov 2026 through 2028)\n2. CURATED_RECENT_RELEASED_BLOCKBUSTERS (38 landmark 2022–2026 released blockbusters with verified actual grosses)\n"""\n\n'
    content += f"CURATED_UPCOMING_TENTPOLES = {json.dumps(updated_upcoming, indent=4)}\n\n"
    content += f"CURATED_RECENT_RELEASED_BLOCKBUSTERS = {json.dumps(CURATED_RECENT_RELEASED_BLOCKBUSTERS, indent=4)}\n"

    with open(CURATED_PATH, "w", encoding="utf-8") as f:
        f.write(content)

    print(f"Successfully updated {CURATED_PATH} with {len(updated_upcoming)} upcoming tentpoles and {len(CURATED_RECENT_RELEASED_BLOCKBUSTERS)} released blockbusters!")

